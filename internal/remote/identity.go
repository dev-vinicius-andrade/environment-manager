// Package remote implements envmgr's parent/child remote control.
//
// A parent ("hub", `envmgr parent serve`) issues single-use, expiring join
// codes. A child (`envmgr join <code>`) dials the parent over TLS, pinning the
// certificate fingerprint carried in the code, enrolls once to obtain its own
// credential, then long-polls the parent for allow-listed profile operations
// and runs them against its local store. Children expose no port; nothing but
// profile operations can ever be executed.
package remote

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/dev-vinicius-andrade/environment-manager/internal/profile"
)

const (
	certFile = "server.crt"
	keyFile  = "server.key"
	// SecretBytes is the size of every random secret (invite secret, agent
	// credential, admin token) before hex encoding.
	SecretBytes = 32
)

// ParentDir returns <ENVMGR_HOME>/parent (hub state).
func ParentDir() (string, error) { return homeSub("parent") }

// AgentDir returns <ENVMGR_HOME>/agent (child binding).
func AgentDir() (string, error) { return homeSub("agent") }

func homeSub(name string) (string, error) {
	d, err := profile.DefaultDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(d, name), nil
}

// Identity is the hub's TLS certificate.
type Identity struct {
	Cert        tls.Certificate
	Fingerprint string // lowercase hex SHA-256 of the leaf certificate DER
	CreatedCert bool   // true when generated by this call
}

// LoadOrCreateIdentity loads the certificate and key from dir, generating
// them if neither exists yet (key file mode 0600).
func LoadOrCreateIdentity(dir string) (*Identity, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, err
	}
	id := &Identity{}
	certPath, keyPath := filepath.Join(dir, certFile), filepath.Join(dir, keyFile)
	certExists, keyExists := fileExists(certPath), fileExists(keyPath)
	switch {
	case !certExists && !keyExists:
		if err := generateCert(certPath, keyPath); err != nil {
			return nil, fmt.Errorf("generate certificate: %w", err)
		}
		id.CreatedCert = true
	case certExists != keyExists:
		return nil, fmt.Errorf("only one of %s and %s exists in %s; delete both to regenerate (every child must re-join)", certFile, keyFile, dir)
	}
	cert, err := tls.LoadX509KeyPair(certPath, keyPath)
	if err != nil {
		return nil, fmt.Errorf("load certificate: %w", err)
	}
	id.Cert = cert
	id.Fingerprint = Fingerprint(cert.Certificate[0])
	return id, nil
}

// Fingerprint returns the lowercase hex SHA-256 of a DER certificate.
func Fingerprint(der []byte) string {
	sum := sha256.Sum256(der)
	return hex.EncodeToString(sum[:])
}

// NormalizeFingerprint accepts hex with optional ':' or spaces, any case, and
// returns 64 lowercase hex chars, or an error.
func NormalizeFingerprint(fp string) (string, error) {
	r := strings.NewReplacer(":", "", " ", "", "-", "")
	s := strings.ToLower(r.Replace(strings.TrimSpace(fp)))
	s = strings.TrimPrefix(s, "sha256")
	if len(s) != 64 {
		return "", fmt.Errorf("invalid fingerprint: want 64 hex chars (SHA-256)")
	}
	if _, err := hex.DecodeString(s); err != nil {
		return "", fmt.Errorf("invalid fingerprint: not hex")
	}
	return s, nil
}

func validSecret(t string) bool {
	if len(t) != SecretBytes*2 {
		return false
	}
	_, err := hex.DecodeString(t)
	return err == nil
}

func generateSecret() (string, error) {
	b := make([]byte, SecretBytes)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

func randomID(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err) // crypto/rand never fails on supported platforms
	}
	return hex.EncodeToString(b)
}

// HashSecret returns the hex SHA-256 of a secret string; only hashes are stored.
func HashSecret(secret string) string {
	sum := sha256.Sum256([]byte(secret))
	return hex.EncodeToString(sum[:])
}

// ctLookup returns the index of the stored hex hash matching secret, or -1.
// Every entry is compared in constant time; it never stops at the first match.
func ctLookup(hashes []string, secret string) int {
	got := sha256.Sum256([]byte(secret))
	idx := -1
	zero := make([]byte, sha256.Size)
	for i, hx := range hashes {
		h, err := hex.DecodeString(hx)
		if err != nil || len(h) != sha256.Size {
			h = zero // malformed entry can never match a real hash
		}
		match := subtle.ConstantTimeCompare(got[:], h)
		unset := subtle.ConstantTimeEq(int32(idx), -1)
		idx = subtle.ConstantTimeSelect(match&unset, i, idx)
	}
	return idx
}

func generateCert(certPath, keyPath string) error {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return err
	}
	now := time.Now()
	tmpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: "envmgr parent"},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.AddDate(10, 0, 0),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		DNSNames:              []string{"localhost"},
		IPAddresses:           []net.IP{net.IPv4(127, 0, 0, 1), net.IPv6loopback},
	}
	if h, err := os.Hostname(); err == nil && h != "" {
		tmpl.DNSNames = append(tmpl.DNSNames, h)
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		return err
	}
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return err
	}
	if err := writeExclusive(keyPath, pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER})); err != nil {
		return err
	}
	if err := writeExclusive(certPath, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})); err != nil {
		_ = os.Remove(keyPath)
		return err
	}
	return nil
}

// writeExclusive creates path with mode 0600, failing if it already exists.
func writeExclusive(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		_ = os.Remove(path)
		return err
	}
	return f.Close()
}

// writeFileAtomic writes data to a 0600 temp file in the same directory and
// renames it over path, retrying briefly (Windows refuses to replace a file
// another process is reading at that instant).
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	tmp := f.Name()
	if err := f.Chmod(0o600); err != nil && !isWindows() {
		f.Close()
		os.Remove(tmp)
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		os.Remove(tmp)
		return err
	}
	if err := f.Close(); err != nil {
		os.Remove(tmp)
		return err
	}
	for i := 0; ; i++ {
		err = os.Rename(tmp, path)
		if err == nil || i >= 50 {
			break
		}
		time.Sleep(10 * time.Millisecond)
	}
	if err != nil {
		os.Remove(tmp)
	}
	return err
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func isWindows() bool { return runtime.GOOS == "windows" }

// IsLoopbackAddr reports whether addr's host is a loopback IP or "localhost".
// An empty host (":7777") binds every interface and is not loopback.
func IsLoopbackAddr(addr string) bool {
	host, _, err := net.SplitHostPort(addr)
	if err != nil {
		return false
	}
	if strings.EqualFold(host, "localhost") {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}

// ValidAddress checks that a is host:port with a non-empty host and numeric port.
func ValidAddress(a string) error {
	host, port, err := net.SplitHostPort(a)
	if err != nil || host == "" {
		return fmt.Errorf("invalid address %q: want host:port", a)
	}
	var n int
	if _, err := fmt.Sscanf(port, "%d", &n); err != nil || n < 1 || n > 65535 || fmt.Sprint(n) != port {
		return fmt.Errorf("invalid port in %q", a)
	}
	return nil
}
