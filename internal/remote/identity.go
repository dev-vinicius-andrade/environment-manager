// Package remote implements the envmgr remote agent: an authenticated HTTPS
// server exposing profile operations only (no command execution), and a client
// that pins the server certificate by SHA-256 fingerprint.
package remote

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/dev-vinicius-andrade/environment-manager/internal/profile"
)

const (
	certFile  = "server.crt"
	keyFile   = "server.key"
	tokenFile = "token"
	// TokenBytes is the size of the random bearer token before hex encoding.
	TokenBytes = 32
)

// DefaultDir returns <ENVMGR_HOME>/remote (see profile.DefaultDir).
func DefaultDir() (string, error) {
	d, err := profile.DefaultDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(d, "remote"), nil
}

// Identity is the server's TLS certificate and bearer token.
type Identity struct {
	Cert         tls.Certificate
	Fingerprint  string // lowercase hex SHA-256 of the leaf certificate DER
	Token        string // hex bearer token; never log it
	CreatedCert  bool   // true when the certificate was generated by this call
	CreatedToken bool   // true when the token was generated by this call
}

// LoadOrCreateIdentity loads the server certificate, key and token from dir,
// generating any that do not exist yet (key and token files are mode 0600).
func LoadOrCreateIdentity(dir string) (*Identity, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, err
	}
	id := &Identity{}
	certPath, keyPath := filepath.Join(dir, certFile), filepath.Join(dir, keyFile)
	certExists, keyExists := fileExists(certPath), fileExists(keyPath)
	switch {
	case !certExists && !keyExists:
		if err := generateCert(certPath, keyPath); err != nil {
			return nil, fmt.Errorf("generate certificate: %w", err)
		}
		id.CreatedCert = true
	case certExists != keyExists:
		return nil, fmt.Errorf("only one of %s and %s exists in %s; delete both to regenerate (clients must re-pair)", certFile, keyFile, dir)
	}
	cert, err := tls.LoadX509KeyPair(certPath, keyPath)
	if err != nil {
		return nil, fmt.Errorf("load certificate: %w", err)
	}
	id.Cert = cert
	id.Fingerprint = Fingerprint(cert.Certificate[0])

	tokPath := filepath.Join(dir, tokenFile)
	b, err := os.ReadFile(tokPath)
	switch {
	case errors.Is(err, os.ErrNotExist):
		tok, err := generateToken()
		if err != nil {
			return nil, err
		}
		if err := writeExclusive(tokPath, []byte(tok+"\n")); err != nil {
			return nil, fmt.Errorf("write token: %w", err)
		}
		id.Token, id.CreatedToken = tok, true
	case err != nil:
		return nil, err
	default:
		id.Token = strings.TrimSpace(string(b))
		if !validToken(id.Token) {
			return nil, fmt.Errorf("token file %s is malformed; delete it to generate a new token", tokPath)
		}
	}
	return id, nil
}

// Fingerprint returns the lowercase hex SHA-256 of a DER certificate.
func Fingerprint(der []byte) string {
	sum := sha256.Sum256(der)
	return hex.EncodeToString(sum[:])
}

// NormalizeFingerprint accepts hex with optional ':' or spaces, any case, and
// returns 64 lowercase hex chars, or an error.
func NormalizeFingerprint(fp string) (string, error) {
	r := strings.NewReplacer(":", "", " ", "", "-", "")
	s := strings.ToLower(r.Replace(strings.TrimSpace(fp)))
	s = strings.TrimPrefix(s, "sha256")
	if len(s) != 64 {
		return "", fmt.Errorf("invalid fingerprint: want 64 hex chars (SHA-256)")
	}
	if _, err := hex.DecodeString(s); err != nil {
		return "", fmt.Errorf("invalid fingerprint: not hex")
	}
	return s, nil
}

func validToken(t string) bool {
	if len(t) != TokenBytes*2 {
		return false
	}
	_, err := hex.DecodeString(t)
	return err == nil
}

// ValidToken reports whether t looks like a token produced by the server.
func ValidToken(t string) bool { return validToken(t) }

func generateToken() (string, error) {
	b := make([]byte, TokenBytes)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

func generateCert(certPath, keyPath string) error {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return err
	}
	now := time.Now()
	tmpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: "envmgr serve"},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.AddDate(10, 0, 0),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		DNSNames:              []string{"localhost"},
		IPAddresses:           []net.IP{net.IPv4(127, 0, 0, 1), net.IPv6loopback},
	}
	if h, err := os.Hostname(); err == nil && h != "" {
		tmpl.DNSNames = append(tmpl.DNSNames, h)
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		return err
	}
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return err
	}
	if err := writeExclusive(keyPath, pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER})); err != nil {
		return err
	}
	if err := writeExclusive(certPath, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})); err != nil {
		_ = os.Remove(keyPath)
		return err
	}
	return nil
}

// writeExclusive creates path with mode 0600, failing if it already exists.
func writeExclusive(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		_ = os.Remove(path)
		return err
	}
	return f.Close()
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}
